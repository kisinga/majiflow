export interface GeneratedFile {
  relativePath: string;
  description: string;
  content: string;
}

export interface GenerateOptions {
  /**
   * Raw site topology JSON — embedded (gzipped) as the /topology.json asset of
   * the local-UI bundle when the topology's local.ui flag is on, so the
   * on-device dashboard boots from the exact site it was generated for.
   */
  topologyJson?: string;
  /**
   * Prebuilt local-UI asset table. The browser build pipeline uses this to make
   * the firmware version and the emitted header depend on the exact same bytes,
   * without fetching `/device-ui/` twice (and risking a deploy between reads).
   */
  localUiAssetsHeader?: string;
}

/**
 * Pinned ESPHome version. The bundle vendors external_components that bind to ESPHome's
 * C++ component API, which shifts across releases — an unpinned bump can break the build.
 * Shipped as requirements.txt and soft-checked in compile.sh. Bump deliberately, with a
 * compile smoke. Keep in sync with the version a CI compile job installs.
 */
